// Difficulty balancer: a greedy bot plays every Adventure level many times
// and we derive move limits, goal sizes and star thresholds from the results.
// Output: public/js/level-tuning.js
//
//   node scripts/balance.js            (all levels)
//   node scripts/balance.js 12         (just print level 12)

import { writeFileSync } from 'node:fs';
import { Game } from '../public/js/engine.js';
import { Rng } from '../public/js/rng.js';
import { levelRecipe, LEVEL_COUNT, tideOf } from '../public/js/levels.js';

const TRIALS = Number(process.env.TRIALS || 30);

// Target win-rate for the bot, by level. Gentle overall decline with a
// sawtooth: each world opens easy and ends with a harder "boss" level.
export function targetWinRate(n) {
  const inWorld = (n - 1) % 10;
  let w = 0.97 - 0.0045 * n - 0.012 * inWorld;
  if (n % 10 === 0) w -= 0.16; // boss levels are the real tests
  if (n <= 3) w = 0.995; // the tutorial should be close to unlosable
  return Math.max(0.5, Math.min(n <= 3 ? 0.995 : 0.98, w));
}

const quantile = (arr, q) => {
  const s = [...arr].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.max(0, Math.floor(q * (s.length - 1))))];
};
const round = (x, to) => Math.max(to, Math.round(x / to) * to);

function configFor(recipe, t, seed) {
  return {
    mode: 'level', rows: recipe.rows, cols: recipe.cols, colors: recipe.colors,
    holes: recipe.holes, jelly: recipe.jelly, crates: recipe.crates, seed,
    ...(tideOf(recipe.n) ? { tideEvery: tideOf(recipe.n) } : {}),
    moves: t.moves, stars: [0, 0, 0],
    objectives: recipe.goals.map((g) =>
      g.type === 'collect' ? { ...g, count: t.collect } : g.type === 'score' ? { ...g, target: t.target } : { ...g }),
  };
}

// A "casual human" bot: plays the goal-aware best move most of the time but
// picks a random legal move 25% of the time.
function botPlay(cfg, rand = 0.1) {
  const g = new Game(cfg);
  const noise = new Rng(cfg.seed ^ 0xabcdef);
  while (g.state === 'playing') {
    const m = noise.next() < rand ? noise.pick(g.allMoves()) : g.smartMove();
    if (!m) break;
    g.swap(m[0], m[1]);
  }
  return g;
}

export function tuneLevel(n) {
  const rand = n % 10 === 0 ? 0 : 0.1;
  const recipe = levelRecipe(n);
  const win = targetWinRate(n);
  const hasScore = recipe.goals.some((g) => g.type === 'score');
  const collect = Math.min(55, 16 + Math.floor(n * 0.6));
  const t = { moves: 0, collect, target: 0, stars: [0, 0, 0] };
  const seeds = Array.from({ length: TRIALS }, (_, i) => 1000 + i * 7);

  if (hasScore && recipe.goals.length === 1) {
    t.moves = Math.min(30, 18 + Math.floor(n / 5));
    const scores = seeds.map((s) => botPlay(configFor(recipe, { ...t, target: 1e12 }, s), rand).score);
    t.target = round(quantile(scores, 1 - win) * (n <= 3 ? 0.7 : 1), 500); // the tutorial levels forgive a casual player
  } else {
    // play with "infinite" moves and record when the goal was reached
    const measure = () => seeds.map((s) => {
      const g = botPlay(configFor(recipe, { ...t, moves: 70 }, s), rand);
      return g.state === 'won' ? g.movesMade : 999;
    });
    let needed = measure();
    // collect goals grow until a level takes real moves (no 2-move wins)
    const hasCollect = recipe.goals.some((g) => g.type === 'collect');
    while (hasCollect && quantile(needed, win) + 1 < 14 && t.collect < 90) { t.collect += 4; needed = measure(); }
    t.moves = Math.max(n <= 8 ? 10 : 7, Math.min(45, quantile(needed, win) + 1));
  }

  // star thresholds from a run at the final move count
  const results = seeds.map((s) => botPlay(configFor(recipe, t, s), rand));
  const winners = results.filter((g) => g.state === 'won').map((g) => g.score);
  const rate = winners.length / results.length;
  const base = hasScore ? t.target : round(quantile(winners.length ? winners : [1000], 0.1), 500);
  let s2 = round(quantile(winners.length ? winners : [base], 0.5), 500);
  let s3 = round(quantile(winners.length ? winners : [base], 0.85), 500);
  if (s2 <= base) s2 = base + 500;
  if (s3 <= s2) s3 = s2 + 1000;
  t.stars = [base, s2, s3];
  return { t, rate, win };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const only = Number(process.argv[2]);
  const out = {};
  const t0 = Date.now();
  for (let n = only || 1; n <= (only || LEVEL_COUNT); n++) {
    const { t, rate, win } = tuneLevel(n);
    out[n] = t;
    const r = levelRecipe(n);
    console.log(`L${String(n).padStart(2)} ${r.goals.map((g) => g.type).join('+').padEnd(14)} moves=${String(t.moves).padStart(2)} collect=${t.collect} target=${t.target} stars=${t.stars.join('/')} botWin=${(rate * 100).toFixed(0)}% (aim ${(win * 100).toFixed(0)}%)`);
  }
  if (!only) {
    const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n');
    writeFileSync(new URL('../public/js/level-tuning.js', import.meta.url),
      `// GENERATED by scripts/balance.js – do not edit by hand.\n// Bot-tuned move limits, goal sizes and star thresholds per level.\nexport const TUNING = {\n${body}\n};\n`);
    console.log(`wrote level-tuning.js in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
  }
}
